 * The symbols the console's own QR encoder (qrcode.react 4.2.0, level L) draws for these texts, one module per bit,
 * rows in order, packed four modules to a hex digit. The encoder is held to them module for module. A text that is
 * a repeated chunk is given as that chunk and its count, so the file stays readable.
 */

