/**
 * The brand assets in the native apps, from the SVGs the console serves
 * (see ./lib/native-brand.mjs for what goes where).
 *
 *   node tools/scripts/generate-native-brand-assets.mjs           # write
 *   node tools/scripts/generate-native-brand-assets.mjs --check   # drift guard
 *
 * The text outputs (SVG copies, asset-catalog JSON, vector drawables) are
 * compared byte for byte. The app icons (PNGs, and the desktop .ico/.icns that
 * hold PNGs) are rendered with sharp (librsvg), whose antialiasing may differ
 * by a bit across machines, so `--check` holds them by what they were
 * rendered FROM: the lock records each icon's size(s) and the sha256 of every
 * source SVG, and a changed source, a missing icon, a wrong size or a wrong
 * transparency is drift.
 */

import { createHash } from 'node:crypto'
import { mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

import {
  appIconSvg,
  BRAND_DIR,
  brandTextOutputs,
  ICNS_TYPES,
  iconContainerCount,
  iconContainers,
  iconRasters,
  iconSources,
  packIcns,
  packIco,
  RETIRED_OUTPUTS,
} from './lib/native-brand.mjs'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..')
const LOCK = 'tools/scripts/native-brand-assets.lock.json'
const sharp = createRequire(join(ROOT, 'package.json'))('sharp')

const readBrand = (name) => readFileSync(join(ROOT, BRAND_DIR, name))
const sha256 = (bytes) => createHash('sha256').update(bytes).digest('hex')
// Each variant is rasterized once, at 2048 (twice the grid), and every size
// is a Lanczos reduction of that, so small sizes keep clean edges.
const MASTER = 2048

const masters = new Map()
async function renderIcon(icon, variant, size) {
  const key = `${icon.name}/${variant}`
  if (!masters.has(key)) {
    const svg = Buffer.from(appIconSvg(icon, readBrand, variant))
    masters.set(
      key,
      await sharp(svg, { density: (72 * MASTER) / 1024 })
        .resize(MASTER, MASTER)
        .png()
        .toBuffer(),
    )
  }
  const image = sharp(masters.get(key)).resize(size, size, {
    kernel: 'lanczos3',
  })
  const opaque = variant === 'full'
  return (opaque ? image.removeAlpha() : image.ensureAlpha())
    .png({ compressionLevel: 9 })
    .toBuffer()
}

async function renderContainer({ icon, format, variant, sizes }) {
  const pngs = await Promise.all(
    sizes.map(async (size) => ({
      size,
      png: await renderIcon(icon, variant, size),
    })),
  )
  if (format === 'ico') return packIco(pngs)
  return packIcns(pngs.map(({ png }, i) => ({ type: ICNS_TYPES[i][0], png })))
}

function readOrNull(file) {
  try {
    return readFileSync(join(ROOT, file))
  } catch {
    return null
  }
}

async function main() {
  const check = process.argv.includes('--check')
  const texts = brandTextOutputs(readBrand)
  const rasters = iconRasters()
  const containers = iconContainers()
  const lock = {
    '//': 'GENERATED by tools/scripts/generate-native-brand-assets.mjs — do not edit. Each app icon, its size(s) and the sha256 of every SVG the icons are drawn from.',
    sources: Object.fromEntries(
      iconSources().map((name) => [
        `${BRAND_DIR}/${name}`,
        sha256(readBrand(name)),
      ]),
    ),
    icons: Object.fromEntries([
      ...rasters.map(({ file, size }) => [file, size]),
      ...containers.map(({ file, sizes }) => [file, sizes]),
    ]),
  }
  const lockContent = `${JSON.stringify(lock, null, 2)}\n`

  if (check) {
    const drifted = []
    for (const { file, content } of [
      ...texts,
      { file: LOCK, content: lockContent },
    ]) {
      const actual = readOrNull(file)
      if (!actual || !actual.equals(Buffer.from(content))) drifted.push(file)
    }
    for (const { file, size, variant } of rasters) {
      const actual = readOrNull(file)
      const meta = actual ? await sharp(actual).metadata() : null
      const opaque = variant === 'full'
      if (
        !meta ||
        meta.width !== size ||
        meta.height !== size ||
        meta.hasAlpha === opaque
      ) {
        drifted.push(
          `${file} (not ${opaque ? 'an opaque' : 'a transparent'} ${size}x${size} PNG)`,
        )
      }
    }
    for (const { file, format, sizes } of containers) {
      const actual = readOrNull(file)
      if (!actual || iconContainerCount(actual, format) !== sizes.length)
        drifted.push(`${file} (not an .${format} of ${sizes.length} images)`)
    }
    for (const file of RETIRED_OUTPUTS)
      if (readOrNull(file)) drifted.push(`${file} (retired; delete it)`)
    if (drifted.length) {
      console.error(
        `${drifted.join('\n')}\nno longer match the console's brand SVGs.\n` +
          'They are generated. Run: node tools/scripts/generate-native-brand-assets.mjs',
      )
      process.exit(1)
    }
    console.log(
      `ok ${texts.length + rasters.length + containers.length + 1} native brand assets`,
    )
    return
  }

  const write = (file, content) => {
    mkdirSync(dirname(join(ROOT, file)), { recursive: true })
    writeFileSync(join(ROOT, file), content)
    console.log(`wrote ${file}`)
  }
  for (const { file, content } of texts) write(file, content)
  for (const { icon, file, size, variant } of rasters)
    write(file, await renderIcon(icon, variant, size))
  for (const container of containers)
    write(container.file, await renderContainer(container))
  for (const file of RETIRED_OUTPUTS) {
    if (readOrNull(file)) {
      rmSync(join(ROOT, file))
      console.log(`removed ${file}`)
    }
  }
  write(LOCK, lockContent)
}

if (process.argv[1] === fileURLToPath(import.meta.url)) await main()
