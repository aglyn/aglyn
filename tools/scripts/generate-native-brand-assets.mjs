/**
 * The brand assets in the native apps, from the SVGs the console serves
 * (see ./lib/native-brand.mjs for what goes where).
 *
 *   node tools/scripts/generate-native-brand-assets.mjs           # write
 *   node tools/scripts/generate-native-brand-assets.mjs --check   # drift guard
 *
 * The text outputs (SVG copies, asset-catalog JSON, vector drawables) are
 * compared byte for byte. The app-icon PNGs are rendered with sharp (librsvg),
 * whose antialiasing may differ by a bit across machines, so `--check` holds
 * them by what they were rendered FROM: the lock records each raster's size
 * and the sha256 of its source SVG, and a changed mark, a missing icon or a
 * wrong size is drift.
 */

import { createHash } from 'node:crypto'
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

import {
  BRAND_DIR,
  brandTextOutputs,
  ICON_ART_FRACTION,
  ICON_GROUND,
  ICON_SOURCE,
  iconRasters,
} from './lib/native-brand.mjs'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..')
const LOCK = 'tools/scripts/native-brand-assets.lock.json'
const sharp = createRequire(join(ROOT, 'package.json'))('sharp')

const readBrand = (name) => readFileSync(join(ROOT, BRAND_DIR, name))
const sha256 = (bytes) => createHash('sha256').update(bytes).digest('hex')

async function renderIcon(size) {
  const svg = readBrand(ICON_SOURCE)
  // Render well above the target, trim to the art, then fit the art into its
  // share of the square on the solid ground.
  const art = await sharp(svg, { density: 72 * 64 }).trim().png().toBuffer()
  const span = Math.round(size * ICON_ART_FRACTION)
  const fitted = await sharp(art).resize(span, span, { fit: 'inside' }).png().toBuffer()
  const { width, height } = await sharp(fitted).metadata()
  return sharp({ create: { width: size, height: size, channels: 3, background: ICON_GROUND } })
    .composite([{ input: fitted, left: Math.round((size - width) / 2), top: Math.round((size - height) / 2) }])
    .flatten({ background: ICON_GROUND })
    .removeAlpha()
    .png({ compressionLevel: 9 })
    .toBuffer()
}

function readOrNull(file) {
  try {
    return readFileSync(join(ROOT, file))
  } catch {
    return null
  }
}

async function main() {
  const check = process.argv.includes('--check')
  const texts = brandTextOutputs(readBrand)
  const rasters = iconRasters()
  const lock = {
    '//': 'GENERATED by tools/scripts/generate-native-brand-assets.mjs — do not edit. Each app icon, its size and the sha256 of the SVG it was rendered from.',
    source: `${BRAND_DIR}/${ICON_SOURCE}`,
    sourceSha256: sha256(readBrand(ICON_SOURCE)),
    icons: Object.fromEntries(rasters.map(({ file, size }) => [file, size])),
  }
  const lockContent = `${JSON.stringify(lock, null, 2)}\n`

  if (check) {
    const drifted = []
    for (const { file, content } of [...texts, { file: LOCK, content: lockContent }]) {
      const actual = readOrNull(file)
      if (!actual || !actual.equals(Buffer.from(content))) drifted.push(file)
    }
    for (const { file, size } of rasters) {
      const actual = readOrNull(file)
      const meta = actual ? await sharp(actual).metadata() : null
      if (!meta || meta.width !== size || meta.height !== size || meta.hasAlpha) drifted.push(`${file} (not an opaque ${size}x${size} PNG)`)
    }
    if (drifted.length) {
      console.error(
        `${drifted.join('\n')}\nno longer match the console's brand SVGs.\n` +
          'They are generated. Run: node tools/scripts/generate-native-brand-assets.mjs',
      )
      process.exit(1)
    }
    console.log(`ok ${texts.length + rasters.length + 1} native brand assets`)
    return
  }

  const write = (file, content) => {
    mkdirSync(dirname(join(ROOT, file)), { recursive: true })
    writeFileSync(join(ROOT, file), content)
    console.log(`wrote ${file}`)
  }
  for (const { file, content } of texts) write(file, content)
  const rendered = new Map()
  for (const { file, size } of rasters) {
    if (!rendered.has(size)) rendered.set(size, await renderIcon(size))
    write(file, rendered.get(size))
  }
  write(LOCK, lockContent)
}

if (process.argv[1] === fileURLToPath(import.meta.url)) await main()
