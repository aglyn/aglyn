/**
 * The mobile apps' theme tokens, compiled from the console's own MUI theme
 * (AGL-3620).
 *
 *   node tools/scripts/generate-mobile-theme-tokens.mjs           # write
 *   node tools/scripts/generate-mobile-theme-tokens.mjs --check   # drift guard
 *
 * The apps cannot import the web theme: it is MUI, and nothing MUI may reach
 * a React Native bundle (check-mobile-isolation). Hand-typing the colors
 * again would let the two drift the first time the palette moves. So this
 * reads the RESOLVED console theme — the same `getConsoleTheme(mode)` the
 * console renders with, light and dark — and writes its palette, shape and
 * spacing as plain data into `libs/mobile/ui`, and the palette, type scale,
 * shape and spacing as Swift and Kotlin source for the native apps
 * (./lib/native-theme.mjs). The web theme is unchanged and
 * the web bundles gain nothing. `--check` runs in the guard sweep, so a
 * palette change that skips this script is red before it ships.
 */

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import {
  KOTLIN_TOKENS_FILE,
  kotlinTokensContent,
  nativeThemeData,
  SWIFT_TOKENS_FILE,
  swiftTokensContent,
} from './lib/native-theme.mjs'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..')
export const TOKENS_FILE = 'libs/mobile/ui/src/lib/tokens.generated.json'
const THEME_SOURCE = 'libs/shared/ui/theme/src/lib/console.theme.ts'

const INTENTS = ['primary', 'secondary', 'tertiary', 'error', 'warning', 'success', 'info']

function intent(color) {
  return {
    main: color.main,
    contrastText: color.contrastText,
    // The accent a word in this color is drawn in on the page ground; the
    // console computes it for contrast (accent-text.ts), so it is read, not
    // re-derived.
    text: color.hoverText ?? color.main,
    pressed: color.hover ?? color.dark ?? color.main,
  }
}

export function tokensFromTheme(theme) {
  const { palette } = theme
  return {
    ...Object.fromEntries(INTENTS.map((name) => [name, intent(palette[name])])),
    background: { default: palette.background.default, paper: palette.background.paper },
    text: {
      primary: palette.text.primary,
      secondary: palette.text.secondary,
      disabled: palette.text.disabled,
    },
    divider: palette.divider,
    grey: Object.fromEntries(
      ['50', '100', '200', '300', '400', '500', '600', '700', '800', '900'].map((key) => [
        key,
        palette.grey[key],
      ]),
    ),
  }
}

export function tokensContent(light, dark) {
  const data = {
    radius: light.shape.borderRadius,
    spacing: Number.parseInt(String(light.spacing(1)), 10),
    light: tokensFromTheme(light),
    dark: tokensFromTheme(dark),
  }
  return `${JSON.stringify(
    {
      '//': [
        'GENERATED by tools/scripts/generate-mobile-theme-tokens.mjs — do not edit.',
        `The console's resolved MUI theme (${THEME_SOURCE}), light and dark, as data for the mobile apps (AGL-3620).`,
      ],
      ...data,
    },
    null,
    2,
  )}\n`
}

async function main() {
  const { createJiti } = createRequire(join(ROOT, 'package.json'))('jiti')
  const jiti = createJiti(join(ROOT, 'package.json'), { interopDefault: true, fsCache: false })
  const theme = await jiti.import(join(ROOT, THEME_SOURCE))
  const light = theme.getConsoleTheme('light')
  const dark = theme.getConsoleTheme('dark')
  // The native apps' Swift and Kotlin tokens (docs/mobile/native-architecture.md §7), from the same resolved theme.
  const native = nativeThemeData(light, dark)
  const outputs = [
    { file: TOKENS_FILE, content: tokensContent(light, dark) },
    { file: SWIFT_TOKENS_FILE, content: swiftTokensContent(native) },
    { file: KOTLIN_TOKENS_FILE, content: kotlinTokensContent(native) },
  ]
  if (process.argv.includes('--check')) {
    const drifted = outputs.filter(({ file, content }) => {
      try {
        return readFileSync(join(ROOT, file), 'utf8') !== content
      } catch {
        return true // Absent is drift.
      }
    })
    if (drifted.length) {
      console.error(
        `${drifted.map(({ file }) => file).join('\n')}\nno longer match the console theme.\n` +
          'They are generated. Run: node tools/scripts/generate-mobile-theme-tokens.mjs',
      )
      process.exit(1)
    }
    for (const { file } of outputs) console.log(`ok ${file}`)
    return
  }
  for (const { file, content } of outputs) {
    mkdirSync(dirname(join(ROOT, file)), { recursive: true })
    writeFileSync(join(ROOT, file), content)
    console.log(`wrote ${file}`)
  }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) await main()
