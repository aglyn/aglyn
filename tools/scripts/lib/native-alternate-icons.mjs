/**
 * The Aglyn app's alternate icons (AGL-3945, Theming → App icon): the logo
 * kit's colored mark on a white ground ("Light") and on the palette's slate
 * ("Dark"), the brand's rule for each ground. Drawn by the same code as the
 * main icon (`appIconSvg`, `adaptiveForeground`), from the same mark SVG, at
 * the same place on the grid, so nothing is re-typed, recolored or moved.
 *
 * Outputs, both platforms, written by generate-native-brand-assets.mjs:
 * - iOS: `AppIcon-Light` and `AppIcon-Dark` icon sets beside `AppIcon`, named
 *   in the Aglyn target's ASSETCATALOG_COMPILER_ALTERNATE_APPICON_NAMES, so the
 *   app's Info.plist lists them under CFBundleAlternateIcons.
 * - Android: `ic_launcher_light` / `ic_launcher_dark` adaptive icons and their
 *   layers, for the app's activity aliases.
 */

import {
  adaptiveBackground,
  adaptiveForeground,
  androidRes,
} from './native-brand.mjs'

const MARK = { source: 'aglyn-logo-mark-multi.svg', x: 212, y: 212, size: 600 }

export const ALTERNATE_ICONS = [
  {
    name: 'Aglyn Light',
    id: 'light',
    appleSet: 'AppIcon-Light',
    layers: ['app-icon/native-icon-ground-light.svg'],
    mark: MARK,
  },
  {
    name: 'Aglyn Dark',
    id: 'dark',
    appleSet: 'AppIcon-Dark',
    layers: ['app-icon/native-icon-ground-dark.svg'],
    mark: MARK,
  },
]

/** The Aglyn app the alternates belong to (its iOS folder and Android module). */
const APPLE_APP = 'Aglyn'
const ANDROID_APP = 'app'

const appleSetDir = (icon) =>
  `apps/ios/${APPLE_APP}/Assets.xcassets/${icon.appleSet}.appiconset`

/** Every brand file an alternate icon is drawn from. */
export const alternateIconSources = () =>
  [
    ...new Set(
      ALTERNATE_ICONS.flatMap((icon) => [...icon.layers, icon.mark.source]),
    ),
  ].sort()

/** The PNGs: each alternate's single 1024 iOS image (iOS draws every size from it). */
export const alternateIconRasters = () =>
  ALTERNATE_ICONS.map((icon) => ({
    icon,
    file: `${appleSetDir(icon)}/AppIcon-1024.png`,
    size: 1024,
    variant: 'full',
  }))

const json = (value) => `${JSON.stringify(value, null, 2)}\n`

const appleSetContents = () =>
  json({
    images: [
      {
        filename: 'AppIcon-1024.png',
        idiom: 'universal',
        platform: 'ios',
        size: '1024x1024',
      },
    ],
    info: { author: 'xcode', version: 1 },
  })

const GENERATED = (icon) =>
  `<!-- GENERATED by tools/scripts/generate-native-brand-assets.mjs from ${[...icon.layers, icon.mark.source].join(', ')} — do not edit. -->`

/** The text outputs: the iOS icon sets' Contents.json, and Android's adaptive icons and layers. */
export function alternateIconTextOutputs(read) {
  const res = androidRes(ANDROID_APP)
  return ALTERNATE_ICONS.flatMap((icon) => {
    const name = `ic_launcher_${icon.id}`
    return [
      { file: `${appleSetDir(icon)}/Contents.json`, content: appleSetContents() },
      {
        file: `${res}/drawable/${name}_background.xml`,
        content: adaptiveBackground(icon, read),
      },
      {
        file: `${res}/drawable/${name}_foreground.xml`,
        content: adaptiveForeground(icon, read),
      },
      {
        file: `${res}/drawable/${name}_monochrome.xml`,
        content: adaptiveForeground(icon, read, { monochrome: true }),
      },
      {
        file: `${res}/mipmap-anydpi-v26/${name}.xml`,
        content:
          `<?xml version="1.0" encoding="utf-8"?>\n${GENERATED(icon)}\n` +
          `<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n` +
          `  <background android:drawable="@drawable/${name}_background" />\n` +
          `  <foreground android:drawable="@drawable/${name}_foreground" />\n` +
          `  <monochrome android:drawable="@drawable/${name}_monochrome" />\n` +
          `</adaptive-icon>\n`,
      },
    ]
  })
}
