/**
 * Per-source attribution of a bundler's EMITTED bytes, read out of the source
 * map the bundler emitted next to them (AGL-2682).
 *
 * `check:aglyn-barrel`, `check:jsx-barrel` and `check:tenant-page-weight` all
 * compute from SOURCE: they answer "what can this entry reach" and "how big is
 * that graph", which is the right question when you are deciding whether an
 * import belongs. None of them can answer the question a Lighthouse report
 * asks — "what is actually inside `42sr79qh0v5oi.js`, and why is the same
 * module in eleven of these files" — because that is a property of the chunker
 * and exists only after a build.
 *
 * `docs/BUILD_PERFORMANCE.md` said that question was unanswerable here, on
 * three grounds that were each true and together wrong:
 *
 * - the webpack analyser reports nothing about a Turbopack build — true, and
 *   irrelevant, because this reads the build output rather than the bundler;
 * - Turbopack production chunks use numeric module ids — true, which is
 *   exactly why the module registry is not the thing to read;
 * - grepping a chunk for a package name is not attribution — true, and this is
 *   not a grep.
 *
 * What none of them ruled out is the instrument Lighthouse itself uses: the
 * `.js.map` beside every chunk carries a `sources` list, and `mappings`
 * assigns every span of GENERATED text to one of them. Decoding it gives real
 * emitted bytes per original module — the same number in the same units the
 * browser downloads.
 *
 * ## What a byte count from here means
 *
 * Generated, unminified-in-the-map-sense bytes: the span between one mapping
 * segment and the next, in the chunk as shipped. Summed over a chunk it comes
 * back within a rounding error of the file's own length, which is the check
 * worth doing on any attribution — {@link attributeChunk} is how, and the
 * report prints the residual so a map that has gone stale announces itself
 * instead of quietly under-counting.
 *
 * A module in two chunks is counted twice, on purpose: that IS the finding.
 * {@link summarize} reports the excess over one copy as `redundant`.
 *
 * ⚠️ Quote gzipped figures when comparing builds. Raw counts on this codebase
 * run 3–4× the transferred size; this module deals in raw because a mapping
 * span has no compressed length, and the CLI gzips the chunk set separately.
 */

const BASE64 =
  'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/'
const DIGIT = new Map([...BASE64].map((char, index) => [char, index]))

const CONTINUATION = 0b100000
const VALUE_MASK = 0b011111
const SHIFT = 5

/**
 * The signed integers packed into one base64 VLQ run.
 *
 * A mapping segment is 1, 4 or 5 of them. Unknown characters are skipped
 * rather than thrown on: a truncated map should degrade to a smaller count,
 * never take the whole report down.
 */
export function decodeVlq(run) {
  const values = []
  let shift = 0
  let value = 0
  for (const char of run) {
    const digit = DIGIT.get(char)
    if (digit === undefined) continue
    value += (digit & VALUE_MASK) << shift
    shift += SHIFT
    if (digit & CONTINUATION) continue
    const negative = value & 1
    values.push(negative ? -(value >> 1) : value >> 1)
    value = 0
    shift = 0
  }
  return values
}

/**
 * Generated bytes per original source, for one chunk and its map.
 *
 * A segment owns the text from its own column up to the next segment on the
 * same generated line, or to the end of that line when it is the last one.
 * Segments of length 1 carry a generated column and no source — real spans of
 * emitted text (bundler runtime, a helper the map does not attribute) — so
 * they close the previous span and are then dropped.
 *
 * `unattributed` is the remainder: chunk length minus everything claimed.
 * Large is not automatically wrong (newlines and the trailing
 * `sourceMappingURL` comment live there), but a residual near the file size
 * means the map does not describe this chunk and the numbers are worthless.
 */
export function attributeChunk(code, map) {
  const lineLengths = code.split('\n').map((line) => line.length)
  const sources = map?.sources ?? []
  const segments = []
  let sourceIndex = 0
  const lines = (map?.mappings ?? '').split(';')
  for (let line = 0; line < lines.length; line++) {
    if (!lines[line]) continue
    let column = 0
    for (const run of lines[line].split(',')) {
      if (!run) continue
      const fields = decodeVlq(run)
      if (!fields.length) continue
      column += fields[0]
      if (fields.length >= 4) {
        sourceIndex += fields[1]
        segments.push([line, column, sourceIndex])
      } else {
        segments.push([line, column, -1])
      }
    }
  }

  const bytes = {}
  let attributed = 0
  for (let i = 0; i < segments.length; i++) {
    const [line, column, source] = segments[i]
    const next = segments[i + 1]
    const end = next && next[0] === line ? next[1] : (lineLengths[line] ?? column)
    const width = Math.max(0, end - column)
    if (source < 0) continue
    const name = sources[source] ?? '(unknown source)'
    bytes[name] = (bytes[name] ?? 0) + width
    attributed += width
  }
  return { bytes, attributed, unattributed: code.length - attributed }
}

/** The npm package a mapped source belongs to, or null for first-party code. */
export function packageOf(source) {
  const match = source.match(/node_modules\/((?:@[^/]+\/)?[^/]+)/)
  return match ? match[1] : null
}

/**
 * Roll per-chunk attributions up into the two numbers worth acting on: which
 * packages are present at all, and which modules were emitted more than once.
 *
 * `redundant` is total minus the largest single copy — what a perfect shared
 * chunk would give back, not what removing the module would.
 */
export function summarize(perChunk) {
  const byModule = {}
  for (const [chunk, bytes] of Object.entries(perChunk))
    for (const [source, size] of Object.entries(bytes))
      (byModule[source] ??= {})[chunk] = size

  const packages = new Map()
  const duplicates = []
  for (const [source, chunks] of Object.entries(byModule)) {
    const sizes = Object.values(chunks)
    const total = sizes.reduce((sum, size) => sum + size, 0)
    const name = packageOf(source)
    const key = name ?? '(first-party)'
    const entry = packages.get(key) ?? { bytes: 0, redundant: 0, modules: 0 }
    entry.bytes += total
    entry.modules += 1
    if (sizes.length > 1) {
      const redundant = total - Math.max(...sizes)
      entry.redundant += redundant
      duplicates.push({
        source,
        copies: sizes.length,
        bytes: total,
        redundant,
        chunks: Object.keys(chunks),
      })
    }
    packages.set(key, entry)
  }

  duplicates.sort((a, b) => b.redundant - a.redundant)
  return {
    packages: [...packages]
      .map(([name, entry]) => ({ name, ...entry }))
      .sort((a, b) => b.bytes - a.bytes),
    duplicates,
    redundantBytes: duplicates.reduce((sum, one) => sum + one.redundant, 0),
  }
}
