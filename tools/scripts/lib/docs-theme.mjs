/**
 * The docs site's interactive colors, compiled from the console's resolved
 * MUI theme by `generate-mobile-theme-tokens.mjs`.
 *
 * Docusaurus paints links and primary buttons from the same Infima variable,
 * so a hand-ported `--ifm-color-primary` puts the brand fill on every link.
 * The console splits them: a Link reads `primary.dark` (`ACCENT_TEXT_SHADE`,
 * held to 4.5:1 as text) and a contained Button fills with `primary.main`
 * and labels with `primary.contrastText`. This writes both slots per scheme,
 * so the docs follow the console and a palette change reaches them through
 * the same `--check` that guards the native tokens.
 */

export const DOCS_TOKENS_FILE = 'apps/docs/src/css/theme-tokens.generated.css'

const HEADER =
  '/* GENERATED by tools/scripts/generate-mobile-theme-tokens.mjs — do not edit.\n' +
  " * Source: the console's resolved MUI theme (libs/shared/ui/theme), light and dark. */"

/**
 * Infima's hover ramp around the fill. The fractions are the ones the
 * Docusaurus docs give for a generated palette.
 */
const RAMP = [
  ['dark', 'darken', 0.1],
  ['darker', 'darken', 0.15],
  ['darkest', 'darken', 0.3],
  ['light', 'lighten', 0.1],
  ['lighter', 'lighten', 0.15],
  ['lightest', 'lighten', 0.3],
]

function schemeBlock(selector, theme, shade) {
  const { primary } = theme.palette
  const lines = [
    `  --ifm-color-primary: ${primary.main};`,
    ...RAMP.map(
      ([name, fn, amount]) =>
        `  --ifm-color-primary-${name}: ${shade[fn](primary.main, amount)};`,
    ),
    `  --ifm-link-color: ${primary.dark};`,
    `  --ifm-link-hover-color: ${primary.dark};`,
    `  --ifm-navbar-link-hover-color: ${primary.dark};`,
    `  --ifm-menu-color-active: ${primary.dark};`,
    `  --ifm-toc-link-color-active: ${primary.dark};`,
    `  --aglyn-button-primary-label: ${primary.contrastText};`,
  ]
  return `${selector} {\n${lines.join('\n')}\n}`
}

/**
 * The CSS file's content.
 *
 * `html[data-theme='dark']`, not the bare attribute: Infima declares its own
 * dark defaults on `html[data-theme='dark']`, which outranks it.
 *
 * @param light the console theme, light scheme
 * @param dark the console theme, dark scheme
 * @param shade `{ darken, lighten }` from `@mui/material/styles`
 */
export function docsTokensContent(light, dark, shade) {
  return (
    [
      HEADER,
      schemeBlock(':root', light, shade),
      schemeBlock("html[data-theme='dark']", dark, shade),
      '/* A primary button labels with the theme\'s contrastText. */\n' +
        '.button.button--primary {\n' +
        '  --ifm-button-color: var(--aglyn-button-primary-label);\n' +
        '}',
    ].join('\n\n') + '\n'
  )
}
