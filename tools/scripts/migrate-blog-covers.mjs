// One-pass blog-cover swap for the aglyn-marketing site (AGL-826/829).
// For each of the four blog covers it: overwrites the Storage object with the
// new logo PNG (generated by generate-blog-covers.mjs), refreshes the media
// doc (contentType/size/contentHash/url + the STABLE hashless cdnPath +
// createdAt if missing + cleared stale variants), and repoints the matching
// blog entry's `coverImage` to that stable cdnPath — so the live covers pick
// up the new art and never break again on replace/move.
//
// Dry-run by default (reads + prints the plan, writes nothing). Pass --commit
// to apply.
//
//   FIREBASE_PROJECT_ID=… FIREBASE_CLIENT_EMAIL=… FIREBASE_PRIVATE_KEY=… \
//   NEXT_PUBLIC_FIREBASE_STORAGE_BUCKET=… \
//     node tools/scripts/migrate-blog-covers.mjs \
//       --covers-dir <dir-with-the-4-pngs> [--host DXnRbPH4CQ] [--commit]
//
// Idempotent: re-running with the same PNGs converges (same hash, same
// cdnPath, coverImage already correct).

import { createHash, randomUUID } from 'node:crypto'
import { existsSync, readFileSync } from 'node:fs'
import { join } from 'node:path'
import { cert, getApps, initializeApp } from 'firebase-admin/app'
import { FieldValue, getFirestore } from 'firebase-admin/firestore'
import { getStorage } from 'firebase-admin/storage'

// Load admin creds from the repo's local env files so this script is
// self-contained (the invocation is a single allow-listed `node …` command;
// secrets are never printed). Already-set process.env wins.
function loadLocalEnv() {
  const roots = ['.', 'apps/console', 'cloud']
  const names = [
    '.env',
    '.env.local',
    '.env.development',
    '.env.development.local',
    '.env.production',
    '.env.production.local',
  ]
  const files = roots.flatMap((r) => names.map((n) => `${r}/${n}`))
  for (const file of files) {
    if (!existsSync(file)) continue
    let text
    try {
      text = readFileSync(file, 'utf8')
    } catch {
      continue
    }
    for (const line of text.split('\n')) {
      const match = line.match(/^\s*(?:export\s+)?([A-Z0-9_]+)\s*=\s*(.*)$/)
      if (!match) continue
      const key = match[1]
      if (process.env[key] !== undefined) continue
      let value = match[2].trim()
      if (
        (value.startsWith('"') && value.endsWith('"')) ||
        (value.startsWith("'") && value.endsWith("'"))
      ) {
        value = value.slice(1, -1)
      }
      process.env[key] = value
    }
  }
}
loadLocalEnv()

const args = process.argv.slice(2)
const flag = (name) => args.includes(name)
const opt = (name, fallback) => {
  const i = args.indexOf(name)
  return i !== -1 ? args[i + 1] : fallback
}

const COMMIT = flag('--commit')
const HOST = opt('--host', 'DXnRbPH4CQ') // aglyn-marketing
const COVERS_DIR = opt('--covers-dir', '')
if (!COVERS_DIR) {
  console.error('Missing --covers-dir <dir with blogCover*.png>')
  process.exit(1)
}

// cover fileName → blog entry slug it illustrates (post-<slug>).
const COVERS = [
  { file: 'blogCoverSurvey.png', entryId: 'post-survey' },
  { file: 'blogCoverMegamenu.png', entryId: 'post-megamenu' },
  { file: 'blogCoverCommerce.png', entryId: 'post-commerce' },
  { file: 'blogCoverMembers.png', entryId: 'post-members' },
]

// ── Admin init (same pattern as seed-changelog.mjs) ─────────────────────────
const projectId = process.env.FIREBASE_PROJECT_ID
if (!projectId) {
  console.error('Missing FIREBASE_PROJECT_ID env var')
  process.exit(1)
}
const bucketName = process.env.NEXT_PUBLIC_FIREBASE_STORAGE_BUCKET
if (!bucketName) {
  console.error('Missing NEXT_PUBLIC_FIREBASE_STORAGE_BUCKET env var')
  process.exit(1)
}
if (!getApps().length) {
  const clientEmail = process.env.FIREBASE_CLIENT_EMAIL
  const privateKey = process.env.FIREBASE_PRIVATE_KEY?.replace(/\\n/g, '\n')
  if (!clientEmail || !privateKey) {
    console.error('Missing FIREBASE_CLIENT_EMAIL / FIREBASE_PRIVATE_KEY env vars')
    process.exit(1)
  }
  initializeApp({ credential: cert({ projectId, clientEmail, privateKey }) })
}
const firestore = getFirestore()
const bucket = getStorage().bucket(bucketName)

console.log(
  `\nBlog-cover migration — host ${HOST} — ${COMMIT ? 'COMMIT' : 'DRY RUN'}\n`,
)

const hostRef = firestore.collection('hosts').doc(HOST)
const mediaCol = hostRef.collection('media')
const entriesCol = hostRef.collection('collections').doc('blog').collection('entries')

let applied = 0
for (const cover of COVERS) {
  // 1. Locate the media doc by fileName.
  const snap = await mediaCol.where('fileName', '==', cover.file).limit(1).get()
  if (snap.empty) {
    console.warn(`SKIP ${cover.file}: no media doc with that fileName`)
    continue
  }
  const mediaDoc = snap.docs[0]
  const mediaId = mediaDoc.id
  const storagePath =
    (mediaDoc.get('storagePath')) || `hosts/${HOST}/media/${mediaId}`
  const cdnPath = `/api/media/cdn/${HOST}/${mediaId}`

  // 2. Read the new PNG + hash it.
  const bytes = readFileSync(join(COVERS_DIR, cover.file))
  const contentHash = createHash('sha256').update(bytes).digest('hex').slice(0, 32)

  // 3. Entry linkage.
  const entryRef = entriesCol.doc(cover.entryId)
  const entryDoc = await entryRef.get()
  const currentCover = entryDoc.exists ? entryDoc.get('coverImage') : '(no entry)'

  console.log(`• ${cover.file}`)
  console.log(`    mediaId      ${mediaId}`)
  console.log(`    storagePath  ${storagePath}`)
  console.log(`    new size     ${(bytes.length / 1024).toFixed(0)} KB  hash ${contentHash.slice(0, 12)}…`)
  console.log(`    cdnPath      ${cdnPath}`)
  console.log(`    entry        ${cover.entryId}  coverImage: ${currentCover}`)

  if (!COMMIT) {
    console.log('    → would overwrite object, refresh doc, set coverImage\n')
    continue
  }

  // 4. Overwrite the Storage object with a fresh download token.
  const token = randomUUID()
  await bucket.file(storagePath).save(bytes, {
    contentType: 'image/png',
    metadata: { metadata: { firebaseStorageDownloadTokens: token } },
  })
  const url =
    `https://firebasestorage.googleapis.com/v0/b/${bucket.name}/o/` +
    `${encodeURIComponent(storagePath)}?alt=media&token=${token}`

  // 5. Refresh the media doc. Clear stale WebP variants so the CDN serves the
  //    new PNG for every width; stamp createdAt if it was missing (so the DAM
  //    default "Newest" sort stops hiding it).
  await mediaDoc.ref.set(
    {
      contentType: 'image/png',
      sizeBytes: bytes.length,
      url,
      cdnPath,
      contentHash,
      variants: [],
      ...(mediaDoc.get('createdAt')
        ? {}
        : { createdAt: FieldValue.serverTimestamp() }),
      updatedAt: FieldValue.serverTimestamp(),
    },
    { merge: true },
  )

  // 6. Repoint the blog entry's cover to the stable URL — but only if it
  //    isn't already pointing there (entries may already carry the absolute
  //    stable URL, which we must NOT downgrade to a relative path).
  const alreadyStable =
    typeof currentCover === 'string' && currentCover.includes(cdnPath)
  if (!entryDoc.exists) {
    console.warn(`    ! entry ${cover.entryId} not found — coverImage not set`)
  } else if (alreadyStable) {
    console.log('    coverImage already stable — left as-is')
  } else {
    await entryRef.set(
      { coverImage: cdnPath, updatedAt: FieldValue.serverTimestamp() },
      { merge: true },
    )
    console.log('    coverImage set to stable cdnPath')
  }
  console.log('    ✓ applied\n')
  applied += 1
}

console.log(
  COMMIT
    ? `Done — ${applied}/${COVERS.length} covers migrated.`
    : `Dry run complete — re-run with --commit to apply.`,
)
process.exit(0)
