// This module's test source set holds the snapshot tool, not tests; the
// shells' UI tests live in libs/native/kotlin/shell.
tasks.withType<Test>().configureEach { failOnNoDiscoveredTests.set(false) }

// Compose copies appResources into the package and the run; on Windows the
// loader is extracted first.
if (isWindows) {
  tasks.matching { it.name == "prepareAppResources" }.configureEach { dependsOn(webview2Loader) }
